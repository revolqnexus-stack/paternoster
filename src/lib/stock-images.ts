export function stockImageRandom(exclude?: string[]) {
  const keys = Object.keys(STOCK_IMAGES).filter(
    (k) => k !== 'fallback' && !(exclude || []).includes(k)
  );
  const randomKey = keys[Math.floor(Math.random() * keys.length)];
  return STOCK_IMAGES[randomKey as keyof typeof STOCK_IMAGES];
}
